// Helper to convert template to Printify product payload
export function toPrintifyPayload(template, variantPrices = {}) {
  return {
    title: template.title,
    description: template.description,
    blueprint_id: template.blueprintId,
    print_provider_id: template.printProviderId,
    variants: template.variants.map((variant, index) => ({
      id: index + 1,
      price: Math.round((variantPrices[variant] || template.basePrice) * 100),
      is_enabled: true,
      options: {
        size: variant
      }
    })),
    print_areas: [
      {
        variant_ids: template.variants.map((_, i) => i + 1),
        placeholders: [
          {
            position: "front",
            images: [
              {
                src: template.logoPath,
                x: 0.5,
                y: 0.5,
                scale: 1.0,
                angle: 0
              }
            ]
          }
        ]
      }
    ]
  };
}
